"""Build a checksummed, portable teacher-SFT bundle from per-run traces."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from sts_agent.learning import export_teacher_sft
from sts_agent.paths import PROJECT_ROOT


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def relative_posix(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


def git_metadata(project_root: Path) -> dict[str, Any]:
    """Return reproducibility metadata without requiring Git to be installed."""

    try:
        revision = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=project_root,
            capture_output=True,
            check=False,
            text=True,
        )
        status = subprocess.run(
            ["git", "status", "--porcelain"],
            cwd=project_root,
            capture_output=True,
            check=False,
            text=True,
        )
    except OSError:
        return {"commit": None, "dirty": None}
    if revision.returncode != 0 or status.returncode != 0:
        return {"commit": None, "dirty": None}
    return {"commit": revision.stdout.strip() or None, "dirty": bool(status.stdout.strip())}


def build_bundle(input_path: Path, output_path: Path, include_traces: bool = False) -> dict[str, Any]:
    """Export valid teacher samples and return the written manifest.

    The output directory must not already exist. This prevents an accidental
    overwrite of a previously checksummed data release.
    """

    paths = export_teacher_sft.trace_paths(input_path)
    if output_path.exists():
        raise ValueError(f"output path already exists: {output_path}")

    output_path.mkdir(parents=True)
    dataset_dir = output_path / "dataset"
    dataset_dir.mkdir()
    traces_dir = output_path / "traces"
    if include_traces:
        traces_dir.mkdir()

    dataset_path = dataset_dir / "teacher-sft.jsonl"
    written = 0
    skipped = 0
    source_traces: list[dict[str, Any]] = []
    screen_counts: Counter[str] = Counter()
    outcome_counts: Counter[str] = Counter()
    teacher_model_counts: Counter[str] = Counter()
    seen_names: set[str] = set()

    with dataset_path.open("w", encoding="utf-8", newline="\n") as output:
        for path in paths:
            records = list(export_teacher_sft.read_jsonl(path))
            outcome = export_teacher_sft.terminal_outcome(records)
            source_info = {
                "name": path.name,
                "bytes": path.stat().st_size,
                "sha256": sha256_file(path),
                "terminal_outcome": outcome,
            }
            source_traces.append(source_info)
            if include_traces:
                if path.name in seen_names:
                    raise ValueError(f"duplicate trace filename: {path.name}")
                seen_names.add(path.name)
                shutil.copy2(path, traces_dir / path.name)
            if outcome is None:
                skipped += len(records)
                continue

            outcome_counts[outcome] += 1
            for record in records:
                sample = export_teacher_sft.export_record(record, outcome)
                if sample is None:
                    skipped += 1
                    continue
                output.write(json.dumps(sample, ensure_ascii=False, separators=(",", ":")) + "\n")
                written += 1
                screen_counts[str(sample.get("screen_type") or "UNKNOWN")] += 1
                teacher = sample.get("teacher")
                if isinstance(teacher, dict) and teacher.get("model_id"):
                    teacher_model_counts[str(teacher["model_id"])] += 1

    bundle_readme = output_path / "README.md"
    bundle_readme.write_text(
        "# StS Teacher SFT Transfer Bundle\n\n"
        "This directory is generated by `python -m sts_agent.learning.training_bundle`. "
        "It contains no API keys, raw CommunicationMod messages, base-model cache, or checkpoints. "
        "Run `sha256sum -c SHA256SUMS` on Linux before training.\n",
        encoding="utf-8",
        newline="\n",
    )

    manifest: dict[str, Any] = {
        "schema_version": "sts-training-bundle-0.1",
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "repository": git_metadata(PROJECT_ROOT),
        "export": {
            "tool": "sts_agent.learning.training_bundle",
            "source": "teacher_auto",
            "requires": ["accepted", "stable_after_action", "action_in_legal_actions", "terminal_run"],
        },
        "dataset": {
            "path": relative_posix(dataset_path, output_path),
            "samples": written,
            "bytes": dataset_path.stat().st_size,
            "sha256": sha256_file(dataset_path),
            "screen_counts": dict(sorted(screen_counts.items())),
            "teacher_model_counts": dict(sorted(teacher_model_counts.items())),
        },
        "source": {
            "input": str(input_path),
            "trace_files": len(paths),
            "included_traces": include_traces,
            "terminal_outcome_counts": dict(sorted(outcome_counts.items())),
            "skipped_records": skipped,
            "traces": source_traces,
        },
    }
    manifest_path = output_path / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")

    checksummed = [dataset_path, bundle_readme, manifest_path]
    if include_traces:
        checksummed.extend(sorted(traces_dir.iterdir()))
    checksum_path = output_path / "SHA256SUMS"
    checksum_path.write_text(
        "".join(f"{sha256_file(path)}  {relative_posix(path, output_path)}\n" for path in checksummed),
        encoding="utf-8",
        newline="\n",
    )
    return manifest


def parse_args() -> argparse.Namespace:
    root = PROJECT_ROOT
    parser = argparse.ArgumentParser(description="Build a checksummed teacher-SFT transfer bundle")
    parser.add_argument("--input", type=Path, default=root / "data" / "trajectories", help="trace file or directory")
    parser.add_argument("--output", type=Path, required=True, help="new bundle directory")
    parser.add_argument("--include-traces", action="store_true", help="copy source action traces for audit and future re-export")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    try:
        manifest = build_bundle(args.input, args.output, include_traces=args.include_traces)
    except (OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    dataset = manifest["dataset"]
    print(
        f"bundle ready: {args.output} | {dataset['samples']} samples | "
        f"{dataset['bytes']} bytes | sha256={dataset['sha256']}",
        flush=True,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
